"""
FastAPI Router for Saman Shop Catalog.
Subsystem: Saman Shop — Boutique Catalog & Curation (CP-SHOP-07).

Provides public read-only catalog access:
- Categories and Curated Collections.
- Paginated and Filtered Product exploration.
- Single Product retrieval by ID.
- Batch Product lookup for Saved/Bookmark syncing.

ADMIN BOUNDARY NOTE:
As per repository governance (AGENTS.md & CP-SHOP-07 specification),
because no secure administrative role boundary exists in the user database,
HTTP write endpoints (POST/PUT/DELETE) are strictly omitted.
Catalog administration (adding, modifying, hiding, publishing, seeding)
is managed through the controlled local CLI: backend.scripts.shop_admin.
"""

from typing import List, Optional
import logging
from fastapi import APIRouter, Depends, HTTPException, Query, status

from backend.app.models.shop import (
    ShopBatchLookupRequest,
    ShopBatchLookupResponse,
    ShopCategoryModel,
    ShopCollectionModel,
    ShopProductPageResponse,
    ShopProductResponse,
)
from backend.app.services.shop_service import (
    ShopInvalidCursorException,
    ShopInvalidQueryException,
    ShopNotFoundException,
    ShopService,
)

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/api/shop", tags=["Shop Catalog"])


def get_shop_service() -> ShopService:
    return ShopService()


@router.get(
    "/categories",
    response_model=List[ShopCategoryModel],
    summary="Get all shop categories",
    description="Returns public active product categories sorted by sortOrder.",
)
async def get_categories(service: ShopService = Depends(get_shop_service)):
    return service.get_categories()


@router.get(
    "/collections",
    response_model=List[ShopCollectionModel],
    summary="Get all curated editorial collections",
    description="Returns public curated collections grouping catalog items.",
)
async def get_collections(service: ShopService = Depends(get_shop_service)):
    return service.get_collections()


@router.get(
    "/products",
    response_model=ShopProductPageResponse,
    summary="List and filter catalog products",
    description="Paginated public product exploration with AND filtering, Vietnamese diacritic-insensitive search, and opaque cursor navigation.",
)
async def get_products(
    query: Optional[str] = Query(None, description="Search keyword matching title, subtitle, or description without diacritics"),
    categoryId: Optional[str] = Query(None, description="Category ID filter (camelCase)"),
    category_id: Optional[str] = Query(None, description="Category ID filter (snake_case fallback)"),
    subcategoryId: Optional[str] = Query(None, description="Subcategory filter (camelCase)"),
    subcategory_id: Optional[str] = Query(None, description="Subcategory filter (snake_case fallback)"),
    collectionId: Optional[str] = Query(None, description="Collection ID filter (camelCase)"),
    collection_id: Optional[str] = Query(None, description="Collection ID filter (snake_case fallback)"),
    pageSize: int = Query(20, ge=1, le=100, description="Page size (default 20, max 100)"),
    page_size: Optional[int] = Query(None, ge=1, le=100, description="Page size fallback"),
    cursor: Optional[str] = Query(None, description="Opaque pagination cursor generated by previous page"),
    service: ShopService = Depends(get_shop_service),
):
    # Normalize parameters between camelCase and snake_case
    resolved_category = categoryId if categoryId is not None else category_id
    resolved_subcategory = subcategoryId if subcategoryId is not None else subcategory_id
    resolved_collection = collectionId if collectionId is not None else collection_id
    resolved_page_size = page_size if page_size is not None else pageSize

    try:
        return service.get_products(
            query=query,
            category_id=resolved_category,
            collection_id=resolved_collection,
            subcategory_id=resolved_subcategory,
            page_size=resolved_page_size,
            cursor=cursor,
        )
    except ShopInvalidCursorException as e:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail={"code": e.code, "message": e.message, "cursor": e.cursor},
        )
    except ShopInvalidQueryException as e:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail={"code": e.code, "message": e.message},
        )


@router.get(
    "/products/{product_id}",
    response_model=ShopProductResponse,
    summary="Get product detail by ID",
    description="Returns product detail for a stable product ID. Throws 404 if not found or hidden.",
)
async def get_product_detail(
    product_id: str,
    service: ShopService = Depends(get_shop_service),
):
    try:
        return service.get_product_by_id(product_id)
    except ShopNotFoundException as e:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail={"code": e.code, "message": e.message, "productId": product_id},
        )


@router.post(
    "/products/batch",
    response_model=ShopBatchLookupResponse,
    summary="Batch lookup products by IDs",
    description="Returns a list of products in the exact requested order. Missing or hidden items return null in their slot.",
)
async def batch_lookup_products(
    payload: ShopBatchLookupRequest,
    service: ShopService = Depends(get_shop_service),
):
    items = service.get_products_by_ids(payload.ids)
    return ShopBatchLookupResponse(items=items)
